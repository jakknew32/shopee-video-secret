export async function fetchShopeeProductData(url: string): Promise<ShopeeProductData | null> {
  const trimmed = url.trim();
  if (!trimmed.startsWith('http')) return null;
  const match = trimmed.match(/shopee\.co\.th\/product\/([0-9]+)\/([0-9]+)/i);
  if (!match) return null;
  const shopId = match[1];
  const itemId = match[2];
  const apiUrl = `https://shopee.co.th/api/v2/item/get?itemid=${itemId}\u0026shopid=${shopId}`;
  try {
    const res = await fetch(apiUrl, { method: 'GET' });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const json = await res.json();
    const data = json.data;
    if (!data) return null;
    const images = data.item_images?.map((img: any) => img?.url) ?? [];
    return {
      title: data.title ?? 'สินค้า',
      price: data.item_price ? (data.item_price / 1000).toString() : '299',
      originalPrice: data.original_price ? (data.original_price / 1000).toString() : undefined,
      discountPercentage: data.discount ? `${data.discount}%` : undefined,
      rating: data.final_rating?.toString() ?? undefined,
      ratingCount: data.final_rating_count?.toString() ?? undefined,
      soldCount: data.amount_sold?.toString() ?? undefined,
      shopLocation: data.shop_location ?? 'Unknown',
      shopName: data.shop_name ?? 'Shopee Store',
      description: data.description ?? 'สินค้า Shopee',
      features: data.features?.map((f: any) => f.title) ?? [],
      productUrl: trimmed,
      affiliateUrl: trimmed,
      images,
    };
  } catch (e) {
    console.warn('Shopee fetch error:', e);
    return null;
  }
}

/**
 * Preload and convert an image URL into an HTMLImageElement
 */
export async function preloadShopeeImage(url: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => resolve(img);
    img.onerror = (e) => reject(e);
    img.src = url;
  });
}
